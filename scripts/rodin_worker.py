def signed_endpoint(url):
    u=urlsplit(url)
    if u.scheme!="https" or u.hostname!="file.hyper3d.com" or u.username:
        raise ValueError("Unexpected Rodin file host")
    return url


async def upload(client, path, kind):
    size=path.stat().st_size
    files = [{"filename": path.name, "size_bytes": size}]
    result = await call_tool(client, "rodin_create_uploads", {"kind": kind, "files": files})
    slot = result["uploads"][0]
    if slot["method"]!="PUT":
        raise ValueError("Unexpected Rodin upload method")
    with path.open("rb") as body:
        headers=dict(slot["headers"])
        headers["Content-Length"]=str(size)
        req=Request(signed_endpoint(slot["upload_url"]),body,headers,method="PUT")
        with rodin_auth.http.open(req,timeout=120) as response:
            if not 200<=response.status<300:
                raise ValueError("Rodin upload failed")
    return slot["upload_id"]


def fingerprint(path):
    with path.open("rb") as stream:
        digest=hashlib.sha256()
        for block in iter(lambda:stream.read(1024*1024),b""):
            digest.update(block)
        return digest.hexdigest()


def perform(job):
    kind=job.kind
    if kind=="status":
        with credential.locked(lambda s:job.progress(None,s)):
            state=credential.load()
        return {"text":"Session saved" if rodin_auth.signed_in(state) else "Sign-in required"}
    def tick(message):
        # Canvas 0.21 only forwards worker stages that include a numeric fraction.
        job.progress(0.0, message)

    if kind=="login":
        rodin_auth.token(tick)
        job.progress(1.0, "Signed in to Rodin")
        return {"text":"Signed in to Rodin"}
    return asyncio.run(run_mesh_job(job, tick))


async def run_mesh_job(job, tick):
    async with connect(tick) as client:
        return await generate(job, tick, client)


async def generate(job, tick, client):
    kind = job.kind
    tick("Connected to Rodin")
    if kind == "image":
        tool="rodin_generate"
        args={"tier":"Gen-2.5-Extreme-Low","geometry_file_format":"glb","mesh_mode":"Raw"}
        path = Path(job["image"])
        if not path.is_file():
            raise ValueError("Connect an image file")
        args["reference_upload_ids"] = [await upload(client, path, "image")]
    else:
        mesh=Path(job["mesh"])
        mapping=credential.state_dir()/"assets"/fingerprint(mesh)
        asset_id=mapping.read_text().strip() if mapping.is_file() else None
        if kind=="bang":
            if not asset_id:raise ValueError("BANG requires a Rodin mesh generated by this extension")
            tool="rodin_generate_bang"
            args={"asset_id":asset_id,"geometry_file_format":"glb","strength":int(job.get("strength",5))}
        elif kind=="rig":
            tool="rodin_generate_rigging"
            args={"bone_template":job.get("bone_template") or "human","geometry_file_format":"glb"}
            if asset_id:args["asset_id"]=asset_id
            else:args["model_upload_id"]=await upload(client,mesh,"model")
        else:raise ValueError("Unknown Rodin job")
    tick("Submitting one Rodin job")
    submission = await call_tool(client, tool, args)
    task = submission["generation_id"]
    tick(f"Rodin job {task} submitted")
    deadline=time.monotonic()+1200
    while time.monotonic()<deadline:
        job.raise_if_cancelled()
        result = await call_tool(client, "rodin_wait", {"generation_id": task, "timeout_seconds": 20})
        if result["status"]=="completed":break
        if result["status"] in ("failed","cancelled","canceled","error"):
            raise RuntimeError(f"Rodin job {task} failed")
        tick(f"Waiting for Rodin job {task}")
        await asyncio.sleep(2)
    else:raise RuntimeError(f"Timed out waiting for Rodin job {task}")
    result = await call_tool(client, "rodin_get_result", {"generation_id": task})
    files = result["files"]
    glbs=[f for f in files if f["name"].lower().endswith(".glb")]
    if not glbs:raise ValueError("Rodin returned no GLB")
    model=next((f for f in glbs if "pbr" in f["name"].lower()),glbs[0])
    out=Path(job["out_dir"]);out.mkdir(exist_ok=True,parents=True)
    dest=out/"rodin.glb"; tmp=dest.with_suffix(".part")
    try:
        with rodin_auth.http.open(signed_endpoint(model["url"]),timeout=120) as response,tmp.open("wb") as file:
            while block:=response.read(1024*1024):
                job.raise_if_cancelled()
                file.write(block)
        with tmp.open("rb") as f:magic,v,size=struct.unpack("<4sII",f.read(12))
        if magic!=b"glTF" or v!=2 or size!=tmp.stat().st_size:raise ValueError("Invalid Rodin GLB")
        tmp.replace(dest)
    finally:tmp.unlink(missing_ok=True)
    if kind == "image":
        cache=credential.state_dir()/"assets";cache.mkdir(exist_ok=True,parents=True)
        (cache/fingerprint(dest)).write_text(task)
    return {"glb_path":str(dest.resolve()),"generation_id":task}


def handle(job):
    # The host prints tracebacks, so keep HTTP URLs and credentials out of errors.
    try:return perform(job)
    except (OSError,KeyError,json.JSONDecodeError,struct.error) as exc:
        raise RuntimeError(f"Rodin operation failed ({type(exc).__name__})") from None


if __name__=="__main__":
    serve("RODINCANVAS",{k:handle for k in ("login","status","image","rig","bang")})
